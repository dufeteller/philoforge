// Reproducible coverage inventory. Source text is never counted as a proof.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const corpus = require('../website/dist/data/ethics.json');
const propositions = corpus.items.filter(item => item.kind === 'Proposition');
assert.equal(propositions.length, 259);
const rows = propositions.map(item => {
  const checked = item.status === 'lean-checked';
  assert.ok(!checked || item.theorem, `Missing theorem: ${item.id}`);
  return `| ${item.id} | ${checked ? 'Scoped reconstruction' : 'Not formalized'} | ${checked ? '`' + item.theorem + '`' : '—'} |`;
});
const checked = propositions.filter(item => item.status === 'lean-checked').length;
const text = [
  '# Ethics: formalization coverage', '',
  'Generated by `node scripts/check-ethics-coverage.cjs --write`.', '',
  `${propositions.length} numbered propositions: ${checked} scoped reconstructions, ${propositions.length - checked} not formalized.`, '',
  'A compiled reconstruction verifies its explicitly encoded statement and hypotheses. It does not establish the fidelity of an interpretation to the historical text. Definitions and assumed premises are not proved propositions. Auxiliary lemmas and countermodels do not increase this count.', '',
  'See [the formalization audit](spinoza-formalization-audit.md) and [candidate foundations](spinoza-foundations.md). Independent philosophical review is pending for every reconstruction.', '',
  '| Proposition | Coverage | Lean declaration |', '| --- | --- | --- |', ...rows, ''
].join('\n');
const target = path.join(__dirname, '../docs/ethics-coverage.md');
if (process.argv.includes('--write')) fs.writeFileSync(target, text);
else assert.equal(fs.readFileSync(target, 'utf8'), text, 'Regenerate Ethics coverage inventory');
console.log(`Coverage: ${checked}/259 scoped reconstructions; ${259 - checked} not formalized.`);
