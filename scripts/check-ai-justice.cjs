// Bind every displayed result and downloadable proof to the compiled source.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const sourcePath = path.join(root, 'logic/PhiloForge/AIJustice.lean');
const source = fs.readFileSync(sourcePath, 'utf8');
const dataPath = path.join(root, 'website/archive/ai-justice/data/ai-justice.json');
const data = JSON.parse(fs.readFileSync(dataPath, 'utf8'));
const write = process.argv.includes('--write');
assert.equal(data.leanVersion, fs.readFileSync(path.join(root, 'logic/lean-toolchain'), 'utf8').trim().split(':v')[1]);
assert.ok(!/\b(sorry|admit|native_decide)\b|^axiom\s/m.test(source));
const ids = data.premises.map(p => p.id);
const proofEntries = [...data.results, ...data.conflicts];
const resultIds = proofEntries.map(r => r.id);
assert.equal(new Set([...ids, ...resultIds]).size, ids.length + resultIds.length);
assert.equal(new Set(proofEntries.map(r => r.leanName)).size, proofEntries.length);
for (const id of data.defaultSelection) assert.ok(ids.includes(id));
for (const result of proofEntries) {
  assert.match(result.leanName, /^PhiloForge\.AIJustice\.[a-z_]+$/);
  for (const id of result.requires) assert.ok(ids.includes(id), `Unknown premise: ${id}`);
  for (const id of result.parents) {
    const parent = data.results.find(r => r.id === id);
    assert.ok(parent, `Unknown result: ${id}`);
    for (const premise of parent.requires) assert.ok(result.requires.includes(premise));
  }
  const name = result.leanName.split('.').pop();
  const match = source.match(new RegExp(`^theorem ${name}\\b[\\s\\S]*?(?=^(?:theorem |def |structure |--|/\\*|/-|end )|(?![\\s\\S]))`, 'm'));
  assert.ok(match, `No source theorem: ${name}`);
  const line = source.slice(0, match.index).split('\n').length;
  const proof = {
    code: match[0].trim(),
    line,
    url: `https://github.com/dufeteller/philoforge/blob/main/logic/PhiloForge/AIJustice.lean#L${line}`
  };
  if (write) result.proof = proof;
  else assert.deepEqual(result.proof, proof, `Stale proof text: ${name}`);
}
const names = [...source.matchAll(/^theorem ([a-z_]+)/gm)].map(m => m[1]);
const checks = [
  '-- Generated by scripts/check-ai-justice.cjs --write.',
  '-- All displayed and helper results are checked and their logical dependencies printed.',
  'import PhiloForge.AIJustice', '',
  ...names.flatMap(name => [`#check @PhiloForge.AIJustice.${name}`, `#print axioms PhiloForge.AIJustice.${name}`, ''])
].join('\n');
const artifacts = [
  [path.join(root, 'logic/PhiloForge/AIJusticeChecks.lean'), checks],
  [path.join(root, 'website/archive/ai-justice/proofs/AIJustice.lean'), source]
];
if (write) fs.writeFileSync(dataPath, JSON.stringify(data, null, 2) + '\n');
for (const [filename, expected] of artifacts) {
  if (write) { fs.mkdirSync(path.dirname(filename), {recursive:true}); fs.writeFileSync(filename, expected); }
  else assert.equal(fs.readFileSync(filename, 'utf8'), expected, `Stale artifact: ${filename}`);
}
console.log(`AI justice: ${data.results.length} results + ${data.conflicts.length} conflict proof, ${names.length} compiled audit references, source download synchronized.`);
